export type Complex = [re: number, im: number];
export type Vec3 = [x: number, y: number, z: number];

export interface Snapshot {
  /** null for mixed states (noisy circuits). */
  amplitudes: Complex[] | null;
  probabilities: number[];
  /** Tr(ρ²) of the whole state: 1 for pure states. */
  state_purity: number;
  bloch: Vec3[];
  purity: number[];
  /** Large circuits: this step kept only Bloch vectors and purity (amplitudes and probabilities dropped). */
  reduced?: boolean;
}

export interface Step {
  index: number;
  line: number;
  kind: "gate" | "measure" | "reset" | "noop" | "conditional";
  name: string;
  label: string;
  qubits: number[];
  clbits: number[];
  num_ctrl: number;
  outcome: number | null;
  applied: boolean | null;
}

export interface RunResult {
  num_qubits: number;
  num_clbits: number;
  steps: Step[];
  snapshots: Snapshot[];
  /** Training visualization data, generated by the lesson's analysis.py. */
  analysis?: Record<string, unknown> & { error?: string };
  clbits: number[];
  has_measurement: boolean;
  stdout: string;
  /** Metrics recorded with report(...) in the code. */
  training?: TrainingData;
  /** Lessons without a circuit (framework "python"): the learner's variables. */
  variables?: VariableRow[];
  /** Set when the circuit was too large to keep the full state of every step. */
  truncated?: boolean;
  /** Indices of the snapshots that kept amplitudes and probabilities (only when truncated). */
  full_snapshots?: number[];
  /** Explanation for the learner, shown on steps whose full state was dropped. */
  notice?: string;
}

export interface VariableRow {
  name: string;
  type: string;
  value: string;
}

export interface TrainingData {
  series: Record<string, number[]>;
}

export type ExportFormat = "qasm3" | "qasm2";

export interface ExportResult {
  format: ExportFormat;
  text: string;
}

export interface EngineError {
  message: string;
  line: number | null;
  kind: string;
}

export interface ValidationResult {
  passed: boolean;
  code: string;
  message: string;
  fidelity: number | null;
  line: number | null;
}

export interface ShotsResult {
  shots: number;
  counts: Record<string, number>;
  measured: "clbits" | "qubits";
  width: number;
}

export interface CatalogSection {
  /** Stable key of the lesson, unchanged when lessons are renumbered. */
  key?: string;
  id: string;
  title: string;
  summary: string;
  available: boolean;
  project?: boolean;
  has_challenge?: boolean;
  estimated_minutes?: number | null;
  /** What the learner will be able to do by the end of the lesson. */
  objectives?: string[];
}

export interface GlossaryEntry {
  term: string;
  aliases?: string[];
  definition: string;
  /** Lesson that introduces the term. */
  lesson: string;
}

export interface CatalogTrack {
  id: number;
  title: string;
  level: string;
  /** The track has an end-of-track review. */
  review?: boolean;
  sections: CatalogSection[];
}

export interface Catalog {
  tracks: CatalogTrack[];
}

export interface LessonProgress {
  code: string | null;
  completed: boolean;
  hints_used: number;
  /** Unsuccessful Check attempts. */
  attempts?: number;
  /** The annotated solution has already been opened. */
  solution_seen?: boolean;
  /** Completed after seeing the solution. */
  with_solution?: boolean;
}

/** End-of-track review question. */
export interface ReviewQuestion {
  /** Lesson to reread when the answer is wrong. */
  lesson: string;
  question: string;
  options: string[];
  answer: number;
  explanation: string;
}

export interface Prediction {
  question: string;
  options: string[];
  answer: number;
  explanation: string;
}

export interface SearchResult {
  id: string;
  track: number;
  title: string;
  snippet: string;
}

/** A note: free text of the learner, saved under "general" or "lesson:<id>". */
export interface Note {
  body: string;
  updated_at: string;
}

export type Notes = Record<string, Note>;

/** Note found by the search. */
export interface NoteHit {
  key: string;
  lesson_id: string | null;
  title: string | null;
  snippet: string;
  updated_at: string;
}

export interface Reference {
  kind: "book" | "paper" | "course" | "tutorial";
  title: string;
  authors: string;
  year?: number;
  /** Where to read: section, title and pages (books) or lecture and section (courses). */
  location: string;
  url: string;
}

export type VisualizerKind =
  | "bloch" | "qsphere" | "compare" | "amplitudes" | "dials" | "histogram" | "modular"
  | "landscape" | "convergence" | "dissociation" | "graph" | "boundary" | "threshold" | "curve" | "variables";

export interface LessonControl {
  id: string;
  options: (string | number | null)[];
  default: string | number | null;
  label: string;
  option_labels: Record<string, string>;
}

export interface Comparison {
  source_qubit: number;
  /** Code span: the source state is that of the line where it appears. */
  source_marker: string;
  target_qubit: number;
  source_label: string;
  target_label: string;
}

export interface Lesson {
  id: string;
  track: number;
  title: string;
  summary: string;
  estimated_minutes?: number;
  num_qubits: number;
  mission: string;
  /** What the learner will be able to do by the end of the lesson. */
  objectives: string[];
  /** Optional challenge, unlocked after the mission. */
  challenge?: { mission: string; hints: string[] };
  /** End-of-track project. */
  project?: boolean;
  prediction?: Prediction;
  hints: string[];
  theory: string;
  starter_code: string;
  default_visualizer: VisualizerKind;
  available_visualizers: VisualizerKind[];
  comparison?: Comparison;
  /** Qubits shown in the amplitude, phase and histogram visualizations. */
  register?: { qubits: number[] };
  modular?: { a: number; N: number };
  framework?: "qiskit" | "pennylane" | "python";
  /** false: the code runs only from the Run button (long training runs). */
  live?: boolean;
  controls?: LessonControl[];
  references?: Reference[];
  lang: string;
}
